assert.equal(worldClock(new Date('2026-01-01T12:00:00Z'),'America/New_York').offset,'GMT-5');
assert.equal(worldClock(new Date('2026-10-31T23:30:00Z'),'Asia/Shanghai').date.slice(0,10),'2026-11-01');
