export function filterProtocols({query='',category='',layer=''}={}){const words=query.trim().toLowerCase().split(/\s+/).filter(Boolean);return protocols.filter(p=>(!category||p.category===category)&&(!layer||p.layer===layer)&&words.every(w=>[p.name,p.category,p.layer,p.ports,p.transport,p.description].join(' ').toLowerCase().includes(w)));}
