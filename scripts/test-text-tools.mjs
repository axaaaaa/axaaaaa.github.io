import assert from 'node:assert/strict';
import {asciiArt} from '../src/utils/ascii-art.mjs';
import {countText} from '../src/utils/character-statistics.mjs';
assert.equal(asciiArt('a').text,asciiArt('A').text);
assert.equal(asciiArt('A').text.split('\n').length,7);
assert.equal(asciiArt('A\nB').text.split('\n').length,15);
assert.equal(asciiArt('').text,'');
assert.deepEqual(asciiArt('中').unsupported,['中']);
assert.throws(()=>asciiArt('a',{ink:'中'}));
assert.throws(()=>asciiArt('a'.repeat(201)));
assert(/^[\x20-\x7e\n]*$/.test(asciiArt('Hello 123!?').text));
assert.equal(countText('').lines,0);
const s=countText('中文 Hello 12\r\n👩‍💻');
assert.equal(s.han,2);assert.equal(s.words,1);assert.equal(s.digits,2);assert.equal(s.lines,2);assert.equal(s.emojis,1);
assert.equal(countText('e\u0301').graphemes,1);assert.equal(countText('e\u0301').codePoints,2);
assert.equal(countText('🇨🇳').emojis,1);
assert.equal(countText('a\n').lines,2);
assert.equal(countText('中').bytes,3);
